const tables: Record<Locale, Table> = { en, hinglish, hi };

export function t(locale: Locale, key: string, vars: Record<string, string | number> = {}, tone: Tone = "warm"): string {
  const v = tables[locale][key] ?? en[key];
  if (v === undefined) return key;
  const s = typeof v === "string" ? v : (v[tone] ?? v.warm ?? Object.values(v)[0] ?? key);
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function makeT(locale: Locale, tone: Tone) {
  return (key: string, vars?: Record<string, string | number>) => t(locale, key, vars, tone);
}

export function hasKey(locale: Locale, key: string): boolean {
  return tables[locale][key] !== undefined;
}
export const allKeys = Object.keys(en);
