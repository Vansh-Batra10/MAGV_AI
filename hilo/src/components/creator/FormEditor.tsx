"use client";
import { useTranslations } from "next-intl";
import { Plus, Trash2 } from "lucide-react";
import { PhotoPicker } from "./PhotoPicker";
import { CityPicker, type CityValue } from "./CityPicker";
import { SongInput } from "./SongInput";
import { VoiceRecorder } from "@/components/media/VoiceRecorder";
import { uploadBlob } from "@/lib/client/upload";
import { setPath } from "@/lib/paths";
import type { TemplateDef } from "@/templates/types";

const PHOTO_KEYS = new Set(["photo", "coverPhoto", "memoryPhoto"]);
const LONG_KEYS = new Set(["letter", "message", "organiserNote", "apology", "memoryCaption", "promise", "extraScene", "threadLine", "closing", "wish", "finale"]);
const HIDDEN = new Set(["sample"]);

function humanize(k: string) {
  return k.replace(/([A-Z])/g, " $1").replace(/^./, (c) => c.toUpperCase());
}

/**
 * Schema form editor ("Edit details"): auto-generated by walking the template's content shape.
 * Handles strings, numbers, photo URLs, photo arrays, cities, songs, voice notes, string arrays and object arrays.
 */
export function FormEditor({ tpl, content, onChange }: { tpl: TemplateDef; content: any; onChange: (c: any) => void }) {
  const t = useTranslations("creator");
  const label = (k: string) => (t.has(`fields.${k}`) ? t(`fields.${k}`) : humanize(k));
  const set = (path: string, v: unknown) => onChange(setPath(content, path, v));
  const variantQ = tpl.questions.find((q) => q.kind === "choice");

  const field = (key: string, value: any, path: string): React.ReactNode => {
    if (HIDDEN.has(key)) return null;
    if (key === "variant" && variantQ?.choices) {
      return (
        <Row key={path} label={label(key)}>
          <div className="flex flex-wrap gap-2">
            {variantQ.choices.map((c) => (
              <button key={c.value} type="button" onClick={() => set(path, c.value)} className={`h-10 rounded-full border px-4 text-sm ${value === c.value ? "border-rose-500 bg-rose-500/15 text-hi" : "border-white/10 text-mid"}`}>{c.label.en}</button>
            ))}
          </div>
        </Row>
      );
    }
    if (key === "photos" && Array.isArray(value)) return <Row key={path} label={label(key)}><PhotoPicker value={value} onChange={(v) => set(path, v)} max={tpl.meta.photosMax} /></Row>;
    if (PHOTO_KEYS.has(key)) return <Row key={path} label={label(key)}><PhotoPicker value={value ? [value] : []} onChange={(v) => set(path, v[0] ?? "")} max={1} /></Row>;
    if (key === "voiceUrl") return <Row key={path} label={label(key)}><VoiceRecorder value={value || null} onClear={() => set(path, "")} onBlob={async (b) => set(path, await uploadBlob(b, "voice"))} /></Row>;
    if ((key === "yourCity" || key === "theirCity") && value && typeof value === "object") return <Row key={path} label=""><CityPicker label={label(key)} value={value} onChange={(c: CityValue) => set(path, c)} /></Row>;
    if (key === "song") return <Row key={path} label={label(key)}><SongInput value={value?.url ?? ""} title={value?.title ?? ""} onChange={(v) => set(`${path}.url`, v)} onTitle={(v) => set(`${path}.title`, v)} /></Row>;
    if (typeof value === "number" || key === "age" || key === "year") {
      return <Row key={path} label={label(key)}><input type="number" inputMode="numeric" value={value ?? ""} onChange={(e) => set(path, e.target.value === "" ? "" : Number(e.target.value))} className={inputCls} /></Row>;
    }
    if (typeof value === "string") {
      return (
        <Row key={path} label={label(key)}>
          {LONG_KEYS.has(key) || value.length > 70 ? (
            <textarea value={value} onChange={(e) => set(path, e.target.value)} rows={key === "letter" ? 8 : 3} className={`${inputCls} h-auto py-3 leading-relaxed`} />
          ) : (
            <input value={value} onChange={(e) => set(path, e.target.value)} className={inputCls} />
          )}
        </Row>
      );
    }
    if (Array.isArray(value)) {
      const isObj = value.length > 0 && typeof value[0] === "object";
      const template = isObj ? Object.fromEntries(Object.entries(value[0]).map(([k, v]) => [k, typeof v === "number" ? 0 : ""])) : "";
      return (
        <Row key={path} label={label(key)}>
          <div className="flex flex-col gap-3">
            {value.map((item: any, i: number) => (
              <div key={i} className="relative rounded-2xl border border-white/8 bg-white/[0.03] p-3 pr-12">
                {isObj ? (
                  <div className="flex flex-col gap-2">{Object.entries(item).map(([k, v]) => field(k, v, `${path}.${i}.${k}`))}</div>
                ) : (
                  <input value={item} onChange={(e) => set(`${path}.${i}`, e.target.value)} className={inputCls} aria-label={`${label(key)} ${i + 1}`} />
                )}
                <button type="button" onClick={() => set(path, value.filter((_: unknown, k: number) => k !== i))} aria-label={t("removeItem")} className="absolute right-2 top-2 grid h-9 w-9 place-items-center rounded-full text-lo hover:text-rose-400"><Trash2 size={16} /></button>
              </div>
            ))}
            {value.length < 12 && (
              <button type="button" onClick={() => set(path, [...value, template])} className="inline-flex h-10 items-center gap-1.5 self-start rounded-full bg-white/5 px-4 text-sm text-mid hover:text-hi"><Plus size={14} /> {t("addItem")}</button>
            )}
          </div>
        </Row>
      );
    }
    if (value && typeof value === "object") return <div key={path} className="flex flex-col gap-3">{Object.entries(value).map(([k, v]) => field(k, v, `${path}.${k}`))}</div>;
    return null;
  };

  return <div className="flex flex-col gap-5">{Object.entries(content ?? {}).map(([k, v]) => field(k, v, k))}</div>;
}

const inputCls = "h-12 w-full rounded-2xl border border-white/10 bg-black/25 px-4 text-[16px] text-hi placeholder:text-lo focus:border-[rgba(var(--glow-rgb),0.6)] focus:outline-none";

function Row({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div>
      {label && <p className="mb-1.5 text-xs font-semibold uppercase tracking-[0.14em] text-lo">{label}</p>}
      {children}
    </div>
  );
}
